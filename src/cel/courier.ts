/** The gesture: author upright, then bend everything along one line of action. */
const ease = (a: number, b: number, v: number): number => { const t = Math.min(1, Math.max(0, (v - a) / (b - a))); return t * t * (3 - 2 * t) }
export const G: Map2 = ([x, y]) => {
  const hip = ease(560, 1080, y)
  const foot = ease(1080, 1620, y)
  const dx = lerp(-34, 34, hip) - foot * 70
  const tilt = lerp(0.085, -0.07, hip) + foot * 0.05
  return [x + dx, y + tilt * (x - 700)]
}
const L = (s: string, m: Map2 = G): Array<P2> => loop(s).map(m)
const C = (s: string, m: Map2 = G): Array<P2> => curve(s).map(m)
const ln = (s: string, w = 1, ends: InnerLine["ends"] = "both", m: Map2 = G): InnerLine => ({ pts: C(s, m), w, ends })
const soft = (s: string, w = 1, m: Map2 = G): InnerLine => ({ pts: C(s, m), w, ends: "both", soft: true })

const text = (g: Ctx, s: string, at: P2, rot: number, size: number, color: string, weight = 800, spacing = 0, m: Map2 = G): void => {
  g.save()
  const o = m(at), e = m([at[0] + 40, at[1]])
  g.translate(o[0], o[1])
  g.rotate(rot + Math.atan2(e[1] - o[1], e[0] - o[0]))
  g.font = `${weight} ${size}px "Avenir Next Condensed", "Arial Narrow", sans-serif`
  if (spacing) (g as unknown as { letterSpacing: string }).letterSpacing = `${spacing}px`
  g.fillStyle = color
  g.fillText(s, 0, 0)
  g.restore()
}
