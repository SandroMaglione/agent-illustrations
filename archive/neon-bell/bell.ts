/** One solid scalloped hair ring with downward cusps at every hair clump. */
const scallop = (stops: ReadonlyArray<readonly [number, number]>, top: number, bot: number, drop: number, seed: string): string => {
  const r = rng(seed)
  const up: Array<string> = [], lo: Array<string> = []
  stops.forEach(([x, y], i) => {
    const t = i / (stops.length - 1), k = Math.min(1, Math.min(t, 1 - t) * 4 + 0.16)
    up.push(`${x},${(y - top * k).toFixed(1)}!`); lo.push(`${x},${(y + bot * k).toFixed(1)}!`)
    const n = stops[i + 1]
    if (!n) return
    const mx = (x + n[0]) / 2, my = (y + n[1]) / 2, d = drop * (0.75 + r() * 0.5)
    up.push(`${(x * 0.75 + n[0] * 0.25).toFixed(1)},${(my - top * k + d * 0.55).toFixed(1)}`, `${mx},${(my - top * k + d * 0.78).toFixed(1)}`, `${(x * 0.25 + n[0] * 0.75).toFixed(1)},${(my - top * k + d * 0.55).toFixed(1)}`)
    lo.push(`${(x * 0.75 + n[0] * 0.25).toFixed(1)},${(my + bot * k + d * 0.72).toFixed(1)}`, `${mx},${(my + bot * k + d).toFixed(1)}`, `${(x * 0.25 + n[0] * 0.75).toFixed(1)},${(my + bot * k + d * 0.72).toFixed(1)}`)
  })
  return [...up, ...lo.reverse()].join(" ")
}

